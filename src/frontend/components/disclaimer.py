"""
Disclaimer components for NeuroScan AI.

Provides reusable disclaimer banners, result disclaimers, and PDF disclaimer
text to ensure responsible use messaging is consistently displayed throughout
the application.
"""

import streamlit as st


def show_disclaimer_banner() -> None:
    """Display a persistent disclaimer banner at the top of every page.

    This banner uses a visually prominent amber/orange style to clearly
    communicate that the tool is for research and educational purposes only.
    """
    st.markdown(
        """
        <div style="
            background: linear-gradient(90deg, #FFF3CD 0%, #FFEAA7 100%);
            border-left: 5px solid #F39C12;
            padding: 12px 20px;
            border-radius: 0 8px 8px 0;
            margin-bottom: 20px;
            font-size: 0.92rem;
            color: #856404;
        ">
            ⚠️ <strong>Research &amp; Educational Use Only</strong> —
            This tool is not a substitute for professional medical diagnosis.
            Always consult a qualified healthcare professional for clinical decisions.
        </div>
        """,
        unsafe_allow_html=True,
    )


def show_result_disclaimer() -> None:
    """Display a disclaimer alongside every analysis result.

    This provides context-specific warnings about AI prediction limitations
    directly where users view their results.
    """
    st.markdown(
        """
        <div style="
            background-color: #FFF8E1;
            border: 1px solid #FFD54F;
            border-radius: 8px;
            padding: 14px 18px;
            margin: 12px 0;
            font-size: 0.85rem;
            color: #6D4C00;
        ">
            <strong>⚕️ Important Notice:</strong> These results are generated
            by an AI model and are intended for research and educational
            purposes only. They should <strong>not</strong> be used as a basis
            for medical decisions. AI predictions can be incorrect — always
            seek evaluation from a qualified radiologist or neurologist.
        </div>
        """,
        unsafe_allow_html=True,
    )


def get_pdf_disclaimer_text() -> str:
    """Return the full disclaimer text for inclusion in PDF reports.

    Returns:
        Multi-line disclaimer string formatted for PDF documents.
    """
    return (
        "DISCLAIMER — RESEARCH & EDUCATIONAL USE ONLY\n"
        "=" * 50 + "\n\n"
        "This report was generated by NeuroScan AI, an experimental "
        "artificial intelligence tool designed for research and educational "
        "purposes only.\n\n"
        "THIS REPORT DOES NOT CONSTITUTE MEDICAL ADVICE.\n\n"
        "The predictions and visualisations contained herein are produced by "
        "machine-learning models that may be inaccurate, biased, or "
        "incomplete. They have NOT been validated for clinical use and must "
        "NOT be used as the sole basis for any medical decision, diagnosis, "
        "or treatment plan.\n\n"
        "Any clinical interpretation of brain MRI scans should be performed "
        "by a qualified radiologist or neurologist in the context of a full "
        "clinical evaluation.\n\n"
        "The developers and operators of NeuroScan AI accept no liability "
        "for any actions taken based on the contents of this report.\n\n"
        "If you or someone you know has concerns about a neurological "
        "condition, please consult a licensed healthcare professional "
        "immediately."
    )
